from typing import List, Dict


def generate_system_prompt(stock_pool: List[str], stock_names: Dict[str, str]) -> str:
    """
    动态生成系统提示词
    
    Args:
        stock_pool: 股票代码列表
        stock_names: 股票代码到名称的映射
    
    Returns:
        完整的系统提示词
    """
